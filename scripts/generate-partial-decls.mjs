#!/usr/bin/env node
// Generates `src/_partial-decls.ts` that calls `ɵɵngDeclareComponent`
// for every component in @mocha/qml-ng so JIT sees signal inputs.

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, basename } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const COMPONENTS_DIR = join(ROOT, 'src', 'components');
const OUT = join(ROOT, 'src', '_partial-decls.ts');

function extractStringField(text, field) {
  // Look for `field:\s*` followed by a quoted/backtick string.
  const m = text.match(new RegExp(`${field}:\\s*([\`'"])`, 'm'));
  if (!m) return null;
  const quote = m[1];
  const startIdx = m.index + m[0].length;
  if (quote === '`') {
    let i = startIdx;
    while (i < text.length) {
      if (text[i] === '\\') { i += 2; continue; }
      if (text[i] === '`') break;
      i++;
    }
    return text.slice(startIdx, i);
  } else {
    const endIdx = text.indexOf(quote, startIdx);
    return text.slice(startIdx, endIdx);
  }
}

function extractObjectField(text, field) {
  // Find `field:\s*\{` and capture balanced braces.
  const start = text.search(new RegExp(`${field}:\\s*\\{`));
  if (start < 0) return null;
  const openIdx = text.indexOf('{', start);
  let depth = 0;
  for (let i = openIdx; i < text.length; i++) {
    if (text[i] === '{') depth++;
    else if (text[i] === '}') {
      depth--;
      if (depth === 0) return text.slice(openIdx, i + 1);
    }
  }
  return null;
}

function parseFile(filePath) {
  const text = readFileSync(filePath, 'utf8');
  if (!/@Component\s*\(/.test(text)) return null;

  const selectorMatch = text.match(/selector:\s*['"]([^'"]+)['"]/);
  if (!selectorMatch) return null;
  const selector = selectorMatch[1];

  const classMatches = [...text.matchAll(/export\s+class\s+(\w+)/g)];
  if (classMatches.length === 0) return null;
  const className = classMatches[classMatches.length - 1][1];

  const template = extractStringField(text, 'template') || '';
  const host = extractObjectField(text, 'host');
  const stylesStr = extractStringField(text, 'styles');
  const styles = stylesStr
    ? stylesStr.split(/\\n|[\r\n]+/).map(s => s.trim()).filter(Boolean)
    : [];

  const inputs = [];
  const inputRegex = /^\s{2}([a-z]\w*)\s*=\s*input\s*[<(]/gm;
  for (const m of text.matchAll(inputRegex)) {
    const field = m[1];
    inputs.push({ field, publicName: field });
  }

  const outputs = [];
  const outputRegex = /^\s{2}([a-z]\w*)\s*=\s*output\s*[<(]/gm;
  for (const m of text.matchAll(outputRegex)) {
    const field = m[1];
    outputs.push({ field, publicName: field });
  }

  return { className, selector, template, host, styles, inputs, outputs };
}

const files = readdirSync(COMPONENTS_DIR)
  .filter((f) => f.endsWith('.ts') && !f.startsWith('_'))
  .map((f) => join(COMPONENTS_DIR, f));

const components = [];
for (const f of files) {
  const parsed = parseFile(f);
  if (parsed) components.push({ ...parsed, file: basename(f) });
}

const lines = [];
lines.push(`// AUTO-GENERATED. Do not edit.`);
lines.push(`// Generated by scripts/generate-partial-decls.mjs.`);
lines.push(`//`);
lines.push(`// For every @mocha/qml-ng component, calls \`ɵɵngDeclareComponent\` to`);
lines.push(`// register signal-based inputs/outputs with Angular's JIT compiler, then`);
lines.push(`// overrides the \`ɵcmp\` getter installed by the @Component decorator so`);
lines.push(`// the JIT compiler's reflection picks up the partial declaration.`);
lines.push(`// Without this, JIT can't see \`input(...)\` field declarations and reports`);
lines.push(`// NG0303 ("Can't bind to ... since it isn't a known property") for every`);
lines.push(`// \`[input]="..."\` binding in user templates.`);
lines.push(``);
lines.push(`import { ɵɵngDeclareComponent, ɵNG_COMP_DEF } from '@angular/core';`);
lines.push(``);

const seen = new Set();
for (const c of components) {
  if (seen.has(c.className)) continue;
  seen.add(c.className);
  const importPath = `./components/${c.file.replace(/\.ts$/, '')}`;
  lines.push(`import { ${c.className} } from '${importPath}';`);
}

lines.push(``);
for (const c of components) {
  const inputsObj = c.inputs.length === 0
    ? '{}'
    : `{\n      ${c.inputs
        .map((i) => `${i.field}: { classPropertyName: '${i.field}', publicName: '${i.publicName}', isSignal: true, isRequired: false, transformFunction: null }`)
        .join(',\n      ')},\n    }`;
  const outputsObj = c.outputs.length === 0
    ? '{}'
    : `{\n      ${c.outputs
        .map((o) => `${o.field}: '${o.publicName}'`)
        .join(',\n      ')},\n    }`;

  const tmplJs = JSON.stringify(c.template);
  const stylesJs = JSON.stringify(c.styles);
  // NOTE on host bindings: the @Component decorator's `host` field uses the
  // shorthand shape `{ '[attr.x]': 'val', '(event)': 'handler()' }`, but the
  // ɵɵngDeclareComponent facade expects the post-compilation shape
  // `{ attributes, listeners, properties, classAttribute, styleAttribute }`.
  // The two shapes are incompatible, so we never forward the @Component host
  // object to the partial decl — it's `undefined` for all components.
  // For components that DO have host bindings, we also skip the ɵNG_COMP_DEF
  // override entirely (the @Component-built def already includes those
  // bindings); the partial decl call is computed but discarded. This is the
  // same trade-off the original codegen made, just now type-safe.
  const overrideCode = c.host
    ? '// host bindings present: skip ɵcmp override to preserve @Component-built hostBindings'
    : `(${c.className} as any)[ɵNG_COMP_DEF] = _def;`;

  // ɵɵngDeclareComponent returns the def; we override ɵcmp with it so the
  // JIT compiler uses our signal-input-aware definition instead of the
  // legacy-decorator-aware definition that @Component installed.
  lines.push(`{`);
  lines.push(`  const _def = ɵɵngDeclareComponent({`);
  lines.push(`    type: ${c.className},`);
  lines.push(`    selector: '${c.selector}',`);
  lines.push(`    isStandalone: true,`);
  lines.push(`    version: '20.0.0',`);
  lines.push(`    isSignal: true,`);
  lines.push(`    template: ${tmplJs},`);
  lines.push(`    host: undefined,`);
  lines.push(`    styles: ${stylesJs},`);
  lines.push(`    inputs: ${inputsObj},`);
  lines.push(`    outputs: ${outputsObj},`);
  lines.push(`  });`);
  lines.push(`  ${overrideCode}`);
  lines.push(`}`);
  lines.push(``);
}

writeFileSync(OUT, lines.join('\n'), 'utf8');
console.log(`Generated ${OUT} with ${components.length} components (${seen.size} unique).`);
